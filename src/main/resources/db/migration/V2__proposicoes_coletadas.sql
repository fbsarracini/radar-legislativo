-- Parlamentar como cadastrado na casa; só entra quando aparece como autor numa coleta.
CREATE TABLE parlamentar (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte         VARCHAR(50)  NOT NULL,
    id_externo    VARCHAR(50)  NOT NULL,
    nome          VARCHAR(255),
    partido       VARCHAR(30),
    uf            VARCHAR(2),
    foto_url      VARCHAR(500),
    atualizado_em TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_parlamentar_fonte_id UNIQUE (fonte, id_externo)
);

CREATE TABLE proposicao (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte                 VARCHAR(50)  NOT NULL,
    id_externo            VARCHAR(50)  NOT NULL,
    esfera                VARCHAR(30)  NOT NULL,
    casa                  VARCHAR(255),
    sigla                 VARCHAR(20),
    numero                INTEGER,
    ano                   INTEGER,
    ementa                TEXT,
    data_apresentacao     DATE,
    url                   VARCHAR(500),
    -- Quando a coleta viu a proposição pela primeira vez: é o "novo desde a última olhada" do feed.
    primeira_vez_vista_em TIMESTAMPTZ  NOT NULL,
    atualizado_em         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_proposicao_fonte_id UNIQUE (fonte, id_externo)
);

CREATE INDEX ix_proposicao_data_apresentacao ON proposicao (data_apresentacao DESC, id DESC);
CREATE INDEX ix_proposicao_primeira_vez_vista_em ON proposicao (primeira_vez_vista_em DESC);

-- Autores na ordem de assinatura; parlamentar_id fica nulo para autores que não são parlamentares da casa.
CREATE TABLE proposicao_autor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposicao_id  BIGINT       NOT NULL,
    ordem          INTEGER      NOT NULL,
    nome           VARCHAR(255),
    tipo           VARCHAR(100),
    proponente     BOOLEAN      NOT NULL,
    parlamentar_id BIGINT,
    CONSTRAINT fk_proposicao_autor_proposicao FOREIGN KEY (proposicao_id) REFERENCES proposicao (id) ON DELETE CASCADE,
    CONSTRAINT fk_proposicao_autor_parlamentar FOREIGN KEY (parlamentar_id) REFERENCES parlamentar (id),
    CONSTRAINT uk_proposicao_autor_ordem UNIQUE (proposicao_id, ordem)
);

CREATE INDEX ix_proposicao_autor_parlamentar ON proposicao_autor (parlamentar_id);

-- Histórico das coletas; a próxima janela começa a partir da última com SUCESSO.
CREATE TABLE coleta (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte        VARCHAR(50)  NOT NULL,
    de           DATE         NOT NULL,
    ate          DATE         NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    novas        INTEGER      NOT NULL DEFAULT 0,
    existentes   INTEGER      NOT NULL DEFAULT 0,
    erro         TEXT,
    iniciada_em  TIMESTAMPTZ  NOT NULL,
    terminada_em TIMESTAMPTZ
);

CREATE INDEX ix_coleta_fonte_status ON coleta (fonte, status, ate DESC);
