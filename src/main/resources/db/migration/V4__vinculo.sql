-- Ligação candidato do TSE ↔ parlamentar coletado, casada por nome + UF + cargo.
-- SUGERIDO vem do casamento automático; CONFIRMADO/REJEITADO são decisões manuais que o recálculo não toca.
CREATE TABLE vinculo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sq_candidato   VARCHAR(20)  NOT NULL,
    parlamentar_id BIGINT       NOT NULL,
    confianca      VARCHAR(30)  NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    criado_em      TIMESTAMPTZ  NOT NULL,
    decidido_em    TIMESTAMPTZ,
    -- A reimportação do TSE apaga quem saiu do arquivo; o vínculo vai junto.
    CONSTRAINT fk_vinculo_candidato FOREIGN KEY (sq_candidato) REFERENCES candidato (sq_candidato) ON DELETE CASCADE,
    CONSTRAINT fk_vinculo_parlamentar FOREIGN KEY (parlamentar_id) REFERENCES parlamentar (id) ON DELETE CASCADE,
    CONSTRAINT uk_vinculo_candidato_parlamentar UNIQUE (sq_candidato, parlamentar_id)
);

CREATE INDEX ix_vinculo_parlamentar ON vinculo (parlamentar_id);
-- Casamento: candidatos de um cargo numa UF.
CREATE INDEX ix_candidato_uf_cargo ON candidato (uf, cargo_busca);
